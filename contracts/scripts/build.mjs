// Compile src/ with solc-js and write artifacts/<Name>.json ({ abi, bytecode }).
import { readFileSync, writeFileSync, mkdirSync, readdirSync, statSync } from "node:fs";
import { join, relative, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import solc from "solc";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const srcDir = join(root, "src");

function walk(dir) {
  return readdirSync(dir).flatMap((f) => {
    const p = join(dir, f);
    return statSync(p).isDirectory() ? walk(p) : p.endsWith(".sol") ? [p] : [];
  });
}

const sources = {};
for (const file of walk(srcDir)) {
  sources["src/" + relative(srcDir, file).replaceAll("\\", "/")] = { content: readFileSync(file, "utf8") };
}

function findImports(path) {
  const candidates = [join(root, "node_modules", path), join(root, path)];
  for (const c of candidates) {
    try {
      return { contents: readFileSync(c, "utf8") };
    } catch {}
  }
  return { error: "not found: " + path };
}

const input = {
  language: "Solidity",
  sources,
  settings: {
    evmVersion: "cancun",
    viaIR: true,
    optimizer: { enabled: true, runs: 200 },
    outputSelection: { "*": { "*": ["abi", "evm.bytecode.object", "evm.deployedBytecode.object"] } },
  },
};

const out = JSON.parse(solc.compile(JSON.stringify(input), { import: findImports }));
let failed = false;
for (const e of out.errors ?? []) {
  if (e.severity === "error") failed = true;
  console[e.severity === "error" ? "error" : "warn"](e.formattedMessage);
}
if (failed) process.exit(1);

mkdirSync(join(root, "artifacts"), { recursive: true });
for (const [file, contracts] of Object.entries(out.contracts)) {
  if (!file.startsWith("src/")) continue;
  for (const [name, c] of Object.entries(contracts)) {
    if (!c.evm.bytecode.object) continue; // interfaces / libraries with only internal fns
    const runtime = c.evm.deployedBytecode.object.length / 2;
    writeFileSync(
      join(root, "artifacts", name + ".json"),
      JSON.stringify({ contractName: name, abi: c.abi, bytecode: "0x" + c.evm.bytecode.object }, null, 2)
    );
    console.log(`${name.padEnd(16)} runtime ${runtime} bytes${runtime > 24576 ? "  ** OVER 24KB LIMIT **" : ""}`);
  }
}

// Ship ABIs + creation bytecode to the web app (deploy.html deploys from the player's own wallet).
const pick = (file, name) => {
  const c = out.contracts[`src/${file}.sol`][name];
  return { abi: c.abi, bytecode: "0x" + c.evm.bytecode.object };
};
const web = {
  BloomPetals: pick("BloomPetals", "BloomPetals"),
  BloomRenderer: pick("BloomRenderer", "BloomRenderer"),
  Bloomwheel: pick("Bloomwheel", "Bloomwheel"),
  BloomRaid: pick("BloomRaid", "BloomRaid"),
  BloomGuard: pick("BloomGuard", "BloomGuard"),
  BloomPvP: pick("BloomPvP", "BloomPvP"),
  BloomRaidView: pick("BloomRaidView", "BloomRaidView"),
};
writeFileSync(
  join(root, "..", "web", "contract.js"),
  `// Generated by contracts/scripts/build.mjs. Do not edit.
export const CONTRACTS = ${JSON.stringify(web)};
export const ABI = CONTRACTS.Bloomwheel.abi;
export const RAID_ABI = CONTRACTS.BloomRaid.abi;
export const GUARD_ABI = CONTRACTS.BloomGuard.abi;\nexport const PVP_ABI = CONTRACTS.BloomPvP.abi;\nexport const RENDERER_ABI = CONTRACTS.BloomRenderer.abi;
export const VIEW_ABI = CONTRACTS.BloomRaidView.abi;
`
);
console.log("wrote web/contract.js");

// The wallet-free demo also needs the stand-ins for the hamster and the Squeek collection.
const mocks = {
  MockSqueekCore: pick("test/MockSqueekCore", "MockSqueekCore"),
  MockSqueekNFT: pick("test/MockSqueekNFT", "MockSqueekNFT"),
};
writeFileSync(
  join(root, "..", "web", "demo-contracts.js"),
  `// Generated by contracts/scripts/build.mjs. Do not edit. Used only by demo.html.\nexport const MOCKS = ${JSON.stringify(mocks)};\n`
);
console.log("wrote web/demo-contracts.js");
